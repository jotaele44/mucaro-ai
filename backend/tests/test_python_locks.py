"""The hash-pinned Python locks the double-click setup installs from (scripts/lock_python_deps.py)."""

from __future__ import annotations

import re
import runpy
import sys
import tomllib
from pathlib import Path

import pytest

from backend.app.security_gates import parse_hashed_lock
from scripts import lock_python_deps, one_click

ROOT = Path(__file__).resolve().parents[2]
# Which setup platform (sys.platform) installs which lock.
PLATFORM_OF_TARGET = {
    "aarch64-apple-darwin": "darwin",
    "x86_64-apple-darwin": "darwin",
    "x86_64-unknown-linux-gnu": "linux",
    "x86_64-pc-windows-msvc": "win32",
}


def _pins(requirements: list[str]) -> dict[str, str]:
    pins = {}
    for requirement in requirements:
        match = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", requirement.strip())
        assert match, f"pyproject pins must be exact: {requirement}"
        pins[match.group(1).lower().replace("_", "-")] = match.group(2)
    return pins


def _project() -> dict:
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]


def _locked(target: str) -> dict[str, dict]:
    return {component["name"].replace("_", "-"): component for component in parse_hashed_lock(lock_python_deps.lock_path(target))}


def test_every_setup_platform_has_a_lock():
    assert set(lock_python_deps.TARGETS) == set(PLATFORM_OF_TARGET)
    for target in lock_python_deps.TARGETS:
        lock = lock_python_deps.lock_path(target)
        assert lock.is_file(), f"run python scripts/lock_python_deps.py ({target})"
        header = lock.read_text(encoding="utf-8").splitlines()[:2]
        assert header == ["# This file was autogenerated by uv via the following command:", f"#    {lock_python_deps.COMPILE_COMMAND}"]


@pytest.mark.parametrize("target", sorted(PLATFORM_OF_TARGET))
def test_lock_is_fully_hash_pinned(target):
    components = parse_hashed_lock(lock_python_deps.lock_path(target))
    assert components
    for component in components:
        assert component["sha256"], f"{component['name']} is not hash-pinned in {target}"


@pytest.mark.parametrize("target", sorted(PLATFORM_OF_TARGET))
def test_lock_pins_exactly_the_project_versions_for_its_extras(target):
    project = _project()
    extras = lock_python_deps.TARGETS[target]
    wanted = _pins(project["dependencies"])
    for extra in extras:
        wanted.update(_pins(project["optional-dependencies"][extra]))
    locked = _locked(target)
    for name, version in wanted.items():
        assert name in locked and locked[name]["version"] == version, f"{name}=={version} missing from {target}"
    # Extras the setup does not install on this platform stay out of its lock.
    for extra, requirements in project["optional-dependencies"].items():
        if extra not in extras:
            for name in _pins(requirements):
                if name not in wanted:
                    assert name not in locked, f"{name} ({extra}) should not be in {target}"
    assert "setuptools" in locked  # builds the editable project install without an unpinned download


@pytest.mark.parametrize("target", sorted(PLATFORM_OF_TARGET))
def test_lock_extras_match_what_the_setup_installs(monkeypatch, target):
    monkeypatch.setattr(sys, "platform", PLATFORM_OF_TARGET[target])
    module = runpy.run_path(str(ROOT / "scripts/one_click.py"), run_name="lock_extras_test")
    assert tuple(filter(None, module["PYTHON_EXTRAS"].split(","))) == lock_python_deps.TARGETS[target]


def test_setup_only_asks_for_locks_that_exist():
    machines = {"darwin": ("arm64", "x86_64"), "linux": ("x86_64",), "win32": ("AMD64",)}
    for system, names in machines.items():
        for machine in names:
            target = one_click.lock_target(system, machine, "win-amd64")
            assert target in lock_python_deps.TARGETS, (system, machine)


def test_window_dependencies_are_locked_where_the_window_runs():
    assert "pythonnet" in _locked("x86_64-pc-windows-msvc")
    assert "pyobjc-core" in _locked("aarch64-apple-darwin")
    linux = _locked("x86_64-unknown-linux-gnu")
    assert "pywebview" not in linux and "pythonnet" not in linux
